"""Generate ``semantics/INDEX.md``: the compact catalog an agent reads first.

One line per entity, metric and glossary term, grouped by domain, so the agent
can choose what a question needs before asking for full context. The file is
deterministic (sorted, no timestamps) so it diffs cleanly in git.
"""

from __future__ import annotations

from .model import Project

HEADER = """<!-- Generated by `mautoontology index`. Do not edit by hand; edit the YAML files instead. -->
# Semantic layer index

Pick the entities, metrics and terms a question needs, then run
`mautoontology context --entities a,b --metrics m` for joins, filters and warnings.
Status legend: approved = reviewed, proposed = generated and unreviewed, draft = incomplete.
"""


def build_index(project: Project) -> str:
    lines = [HEADER]
    domains = sorted({e.domain or "core" for e in project.entities.values()} | {m.get("domain") or "core" for m in project.metrics.values()})
    for domain in domains:
        lines.append(f"## Domain: {domain}\n")
        entities = sorted((e for e in project.entities.values() if (e.domain or "core") == domain), key=lambda e: e.id)
        if entities:
            lines.append("### Entities\n")
            for entity in entities:
                raw = entity.raw
                grain = ", ".join(raw.get("grain") or ["?"])
                desc = _one_line(raw.get("description"))
                tags = [raw.get("entity_type") or "entity", raw.get("status", "proposed")]
                if (raw.get("history") or {}).get("type"):
                    tags.append(raw["history"]["type"])
                if raw.get("default_filters"):
                    tags.append("default filters")
                lines.append(f"- `{entity.id}` ({', '.join(tags)}) - `{entity.dataset}`, grain: {grain}" + (f" - {desc}" if desc else ""))
                rels = [r for r in project.relationships() if r.from_entity == entity.id]
                if rels:
                    targets = ", ".join(f"{r.to_entity}{' as ' + r.role if r.role else ''} ({r.cardinality.replace('_', ' ')})" for r in rels)
                    lines.append(f"  - joins to: {targets}")
            lines.append("")
        metrics = sorted((m for m in project.metrics.values() if (m.get("domain") or "core") == domain), key=lambda m: m["id"])
        if metrics:
            lines.append("### Metrics\n")
            for metric in metrics:
                synonyms = ", ".join(metric.get("synonyms") or [])
                desc = _one_line(metric.get("description"))
                lines.append(f"- `{metric['id']}` ({metric.get('type')}, {metric.get('status', 'proposed')})"
                             + (f" - {desc}" if desc else "") + (f" - aka: {synonyms}" if synonyms else ""))
                if metric.get("disambiguation"):
                    lines.append(f"  - note: {_one_line(metric['disambiguation'])}")
            lines.append("")
    if project.terms:
        lines.append("## Glossary\n")
        for term_id in sorted(project.terms):
            term = project.terms[term_id]
            targets = ", ".join(term.get("maps_to") or [])
            lines.append(f"- **{term_id}**: {_one_line(term.get('definition'))}" + (f" -> {targets}" if targets else ""))
            if term.get("disambiguation"):
                lines.append(f"  - note: {_one_line(term['disambiguation'])}")
        lines.append("")
    if project.queries:
        lines.append("## Verified queries\n")
        for query_id in sorted(project.queries):
            lines.append(f"- `{query_id}`: {_one_line(project.queries[query_id].get('question'))}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _one_line(text: object, limit: int = 140) -> str:
    if not text:
        return ""
    flat = " ".join(str(text).split())
    return flat if len(flat) <= limit else flat[: limit - 1] + "…"
